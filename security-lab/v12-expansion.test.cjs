'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const body={dataset:{gameMode:'endless'}};
const w={document:{body}};
const runtime={isStoryActive:()=>false,isIsolatedStoryRuntime:()=>false};
const context=vm.createContext({window:w,GameModeRuntime:runtime,Number,Math,Object,Date,Array});
for(const file of ['combat-director-v12.js','narrative-v12.js']){
 vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context,{filename:file});
}
const combat=w.TowerCombatDirectorV12,narrative=w.TowerNarrativeV12;
assert.ok(combat&&narrative);
assert.equal(combat.stage(100,100),1);
assert.equal(combat.stage(64,100),2);
assert.equal(combat.stage(27,100),3);
assert.equal(combat.stage(1,0),1);
const boss={type:'boss',subType:'ranged_boss',hp:100,maxHp:100,speed:20,attackInterval:1.2,x:10,y:20,radius:30};
assert.equal(combat.spawn(boss),true);
assert.equal(boss.v12Combat.phase,1);
boss.hp=60;const rings=[],texts=[];
combat.tick(boss,1/60,{rings,text:(...args)=>texts.push(args)});
assert.equal(boss.v12Combat.phase,2);
assert.equal(combat.volley(boss,[-.17,0,.17]).length,5);
const speedAtPhase2=boss.speed;
for(let i=0;i<100;i++)combat.tick(boss,1/60,{rings,text:()=>{}});
assert.equal(boss.speed,speedAtPhase2,'phase speed must not compound');
boss.hp=24;combat.tick(boss,1/60,{rings,text:()=>{}});
assert.equal(boss.v12Combat.phase,3);
assert.equal(texts.length,1,'phase transition text once');
assert.ok(rings.length>=2,'phase transition rings');
const titan={type:'boss',subType:'tank_boss',hp:100,maxHp:100,speed:14,attackInterval:1.65};
assert.ok(combat.spawn(titan));
titan.hp=20;combat.tick(titan,.02);
assert.ok(combat.mitigation(titan,100)<100,'titan armor matters');
const runner={type:'boss',subType:'speed_boss',hp:100,maxHp:100,speed:60,attackInterval:.8};
combat.spawn(runner);runner.hp=20;combat.tick(runner,.02);
assert.ok(combat.dashCooldown(runner,3)<3,'runner dash speeds up');
const cryo={type:'boss',subType:'frost_boss',hp:100,maxHp:100,speed:20,attackInterval:1.5};
combat.spawn(cryo);cryo.hp=20;combat.tick(cryo,.02);
assert.equal(combat.volley(cryo,[0]).length,5);
assert.ok(combat.frostDuration(cryo,1.15,5)<1.15);
const companions={frostOrb:{unlocked:true},laserDrone:{unlocked:true},plasmaSatellite:{unlocked:true},missileBot:{unlocked:true}};
const enemy={slowTimer:2};
const frostLaser=combat.bonus(enemy,100,'laser',companions,1000);
assert.equal(frostLaser.bonus,9);
assert.equal(combat.bonus(enemy,100,'laser',companions,1400).bonus,0,'shatter cooldown');
const frostPlasma=combat.bonus(enemy,100,'plasma',companions,2000);
assert.equal(frostPlasma.bonus,12);
assert.equal(combat.bonus(enemy,100,'missile',companions,2100).bonus,10,'plasma missile combo');
assert.equal(combat.bonus(enemy,100,'missile',companions,2200).bonus,0,'plasma mark consumed once');
assert.equal(combat.bonus(enemy,100,'missile',{plasmaSatellite:{unlocked:false}},3000).bonus,0,'locked companion gives no bonus');
body.dataset.gameMode='story';
assert.equal(combat.spawn({...boss,v12Combat:undefined}),false,'no story boss stages');
assert.equal(combat.bonus(enemy,100,'laser',companions,4000).bonus,0,'no story combo leakage');
body.dataset.gameMode='endless';
const p={routeChoice:'blackbox',powerChoice:'weapon',voiceChoice:'station',mission4Complete:true,mission12Complete:true,mission21Complete:true,callSignChoice:'echo'};
const session={active:true,mission:19},game={waveTargetKills:5,upgrades:{damage:3}},tower={maxShield:0,shield:0};
const branch=narrative.apply(session,p,game,tower);
assert.equal(branch.id,'blackbox');assert.equal(game.waveTargetKills,7);assert.equal(session.v12Branch,'blackbox');
const another={active:true,mission:20},g2={waveTargetKills:5,upgrades:{damage:3}},t2={maxShield:10,shield:10};
narrative.apply(another,{powerChoice:'shield'},g2,t2);
assert.equal(t2.shield,32);assert.equal(t2.maxShield,32);assert.equal(g2.waveTargetKills,5);
const weapon={active:true,mission:20},g3={waveTargetKills:5,upgrades:{damage:3}},t3={maxShield:0,shield:0};
narrative.apply(weapon,p,g3,t3);assert.equal(g3.waveTargetKills,7);assert.equal(g3.upgrades.damage,5);
assert.equal(narrative.pikoTier(p),3);
assert.match(narrative.pikoLine(p,false,'idle'),/Echo/);
assert.match(narrative.missionLine(19,p,false),/KARAKUTU/);
assert.equal(narrative.branch(18,p),null);
const before=JSON.stringify(p);narrative.apply({active:true,mission:21},p,{waveTargetKills:5,upgrades:{damage:3}},{maxShield:0,shield:0});
assert.equal(JSON.stringify(p),before,'story choice progress must remain unchanged');
console.log('PASS V12: 3 boss phases, 5 archetypes, cooldowns, three combos, story isolation, 3 branching missions, evolving Piko, existing progress untouched');
