'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const element = { dataset: {}, style: {opacity:''}, isConnected: true, setAttribute(){}, textContent:'' };
const body = { dataset: {gameMode:'endless'}, appendChild(){} };
const window = { document:{body,createElement:()=>element}, setTimeout:()=>1, clearTimeout(){}, matchMedia:()=>({matches:true}) };
const source = fs.readFileSync(path.join(__dirname,'..','boss-cinema-v15.js'),'utf8');
vm.runInNewContext(source,{window});
const hud = window.TowerBossCinemaV15;
assert.equal(hud.cue('tank_boss',1),true);
assert.equal(hud.cue('tank_boss',1),false);
element.style.opacity='0';
assert.equal(hud.cue('tank_boss',1),true);
hud.resetEncounter();
assert.equal(hud.cue('tank_boss',1),true);
body.dataset.gameMode='story';
assert.equal(hud.cue('tank_boss',2),false);
console.log('PASS boss alert rearming after fade and reset');
