'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const rootFile=(p)=>path.join(__dirname,'..',p);
const script=fs.readFileSync(rootFile('enemy-motion-v17.js'),'utf8');
const root={navigator:{deviceMemory:8},matchMedia:()=>({matches:false})};
root.window=root;
vm.runInNewContext(script,{window:root,globalThis:root});
const fx=root.TowerEnemyMotionV17;
assert(fx,'motion module exported');
const scout={type:'green',variantId:'scout',radius:13,x:70,y:90,hp:30,maxHp:30,hitFlash:0,animPhase:0.25};
const before=JSON.stringify(scout);
const f=fx.frame(scout,1670);
assert.equal(f.boss,false);
assert(Math.abs(f.bob)<=1.15&&Math.abs(f.tilt)<=0.04);
assert(f.scale>0.98&&f.scale<1.02);
assert.equal(JSON.stringify(scout),before,'visual animation may not mutate combat entity');
assert.equal(fx.frame(null,100),null);
const boss={type:'boss',subType:'frost_boss',radius:33,x:60,y:60,hp:70,maxHp:100,hitFlash:0,v12Combat:{phase:1}};
fx.frame(boss,1000);
boss.v12Combat.phase=2;
const first=fx.frame(boss,1100);
assert.equal(first.phase,2);
const next=fx.frame(boss,1200);
assert(next.transition>0&&next.transition<1,'boss phase transition creates short visual pulse');
const late=fx.frame(boss,1900);
assert.equal(late.transition,0,'phase pulse expires without a timer');
assert.equal(boss.v12Combat.phase,2,'phase unchanged by animation');
const calls=[];
const ctx={
 save(){calls.push('save')},restore(){calls.push('restore')},beginPath(){calls.push('begin')},
 arc(){calls.push('arc')},fill(){calls.push('fill')},stroke(){calls.push('stroke')}
};
fx.under(ctx,{type:'runner',radius:14,subType:'runner'},fx.frame({type:'runner',radius:14},100),28);
assert.equal(calls.filter(c=>c==='fill').length,2,'at most two exhaust points per body');
fx.over(ctx,boss,next,66);
assert(calls.includes('stroke'),'phase transition ring drawn');
const count=calls.length;
fx.setQuality('low');
const low=fx.frame(scout,2000);
assert.equal(low.bob,0);
assert.equal(low.tilt,0);
assert.equal(low.scale,1);
fx.over(ctx,boss,fx.frame(boss,2000),66);
assert(calls.length<=count+5,'low quality does not add persistent visual clutter');
root.matchMedia=()=>({matches:true});
assert.equal(fx.getState().resolved,'low');
assert.equal(fx.getState().reducedMotion,true);
root.matchMedia=()=>({matches:false});
fx.setQuality('normal');
assert.equal(fx.getState().resolved,'normal');
const render=fs.readFileSync(rootFile('render.js'),'utf8');
const adapter=fs.readFileSync(rootFile('enemy-sprites-v17.js'),'utf8');
const index=fs.readFileSync(rootFile('index.html'),'utf8');
assert.match(render,/TowerEnemySpritesV17\.render\(ctx, e, tx, ty, nowCompTime\)/);
assert.match(adapter,/TowerEnemyMotionV17/);
assert(index.indexOf('enemy-motion-v17.js')>=0);
assert(index.indexOf('enemy-motion-v17.js')<index.indexOf('enemy-sprites-v17.js'));
console.log('V17 restrained sprite motion and boss phase visuals passed');
