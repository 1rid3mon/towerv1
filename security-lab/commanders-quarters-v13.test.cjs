const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'../commanders-quarters-v13.js'),'utf8');
const script=new vm.Script(code,{filename:'commanders-quarters-v13.js'});
