'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'..','station-systems-v14.js'),'utf8');
const context=vm.createContext({window:{},Date,Math,Number,Object,Array});
new vm.Script(source,{filename:'station-systems-v14.js'}).runInContext(context);
const api=context.window.TowerStationSystemsV14;
assert.ok(api,'V14 logic exists');
assert.equal(api.anomalyFor(6,false),null);
assert.equal(api.anomalyFor(7,true),null,'story combat must remain isolated');
assert.equal(api.anomalyFor(7,false).id,'fog');
assert.equal(api.anomalyFor(14,false).id,'gravity');
assert.equal(api.anomalyFor(21,false).id,'ion');
assert.equal(api.anomalyFor(35,false),null,'boss wave skipped');
assert.equal(api.anomalyFor(14,false).speed,.82);
assert.equal(api.anomalyFor(7,false).range,.82);
assert.equal(api.anomalyFor(21,false).rate,.85);
assert.equal(api.stationStage(0),0);
assert.equal(api.stationStage(9),1);
assert.equal(api.stationStage(18),2);
assert.equal(api.stationStage(27),3);
assert.equal(api.pikoProfile({voiceChoice:'human'},{bossKills:23}),'human');
assert.equal(api.pikoProfile({callSignChoice:'echo',mission21Complete:true},{}),'echo');
const day='2026-11-04',another='2026-11-05';
assert.equal(api.planFor(day).length,12);
assert.deepEqual(JSON.stringify(api.planFor(day)),JSON.stringify(api.planFor(day)),'same UTC date has same opponents');
assert.notEqual(JSON.stringify(api.planFor(day)),JSON.stringify(api.planFor(another)),'dates are distinct');
let s=api.newRun(day);
assert.equal(s.energy,4);
assert.equal(api.buy(s,9),s,'invalid lane does not change run');
const a=api.buy(s,0);
assert.equal(s.energy,4,'immutable purchase');
assert.equal(a.energy,3);
assert.equal(a.towers[0],1);
assert.equal(api.buy(a,0).energy,1,'upgrade costs two energy');
s=a;
const saved=JSON.stringify(s);
s=api.advance(s);
assert.equal(s.turn,1);
assert.equal(s.energy,4);
assert.equal(JSON.stringify(a),saved,'no in-place mutation');
for(let i=0;i<15&&!s.finished;i++){s=api.advance(s);}
assert.equal(s.finished,true);
assert.ok(s.turn<=15);
assert.ok(api.score(s)>=0);
const finished=api.advance(s);
assert.equal(finished,s,'no turn after finished');
console.log('PASS V14: anomaly isolation, deterministic daily scenario, immutable combat turns, Piko profiles, station progression');


const directorSource=fs.readFileSync(path.join(__dirname,'..','combat-director-v12.js'),'utf8');
const combatContext=vm.createContext({window:{document:{body:{dataset:{gameMode:'endless'}}}},Date,Math,Number,Object,Array});
new vm.Script(directorSource,{filename:'combat-director-v12.js'}).runInContext(combatContext);
const combat=combatContext.window.TowerCombatDirectorV12;
const boss={type:'boss',subType:'leviathan',hp:100,maxHp:100,speed:2,attackInterval:2,x:40,y:40,radius:15};
assert.equal(combat.spawn(boss),true);
boss.hp=60;combat.tick(boss,.1,{});
assert.equal(boss.v12Combat.phase,2);
assert.ok(combat.interference([boss]).rate<1,'phase 2 boss jams tower fire');
combat.tick(boss,3,{});
assert.equal(combat.interference([boss]).rate,1,'jamming expires');
boss.hp=20;combat.tick(boss,.1,{});
assert.equal(boss.v12Combat.phase,3);
assert.ok(combat.interference([boss]).rate<=.5,'phase 3 has stronger interference');
const titan={type:'boss',subType:'tank_boss',hp:50,maxHp:100,speed:1,attackInterval:3,x:0,y:0,radius:16};
combat.spawn(titan);combat.tick(titan,.1,{});
assert.ok(combat.interference([titan]).range<1,'boss temporarily alters combat terrain');
combat.tick(titan,8,{});
assert.equal(combat.interference([titan]).range,1,'terrain returns to normal');

assert.equal(api.verifyReplay('not-a-date',[]).valid,false);
assert.equal(api.verifyReplay('2026-02-30',[]).valid,false);
assert.equal(api.verifyReplay(day,[{type:'buy',lane:9}]).valid,false);
assert.equal(api.verifyReplay(day,[{type:'next'}]).valid,false,'unfinished replays cannot be ranked');
const legal=[];
let replay=api.newRun(day);
for(let i=0;i<15&&!replay.finished;i++){
 if(i===0){replay=api.buy(replay,0);legal.push({type:'buy',lane:0});}
 replay=api.advance(replay);legal.push({type:'next'});
}
const verified=api.verifyReplay(day,legal);
assert.equal(verified.valid,true);
assert.equal(verified.score,api.score(replay));
assert.equal(api.verifyReplay(day,[...legal,{type:'next'}]).valid,false,'post-finish injection rejected');
