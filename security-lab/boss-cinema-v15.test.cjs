'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const node={dataset:{},style:{},isConnected:true,setAttribute(){},textContent:''};
const body={dataset:{gameMode:'endless'},appendChild(){}};
const window={document:{body,createElement:()=>node},setTimeout:()=>1,clearTimeout(){},matchMedia:()=>({matches:true})};
new vm.Script(fs.readFileSync(path.join(__dirname,'..','boss-cinema-v15.js'),'utf8')).runInNewContext({window});
const cinema=window.TowerBossCinemaV15;
assert.equal(cinema.cue('tank_boss',1),true);
assert.equal(cinema.cue('tank_boss',1),false,'duplicate phase suppressed');
assert.equal(cinema.cue('tank_boss',2),true);
assert.equal(cinema.cue('tank_boss',3),true);
assert.equal(cinema.cue('tank_boss',3),false);
cinema.resetEncounter();
assert.equal(cinema.cue('tank_boss',1),true,'next encounter can reuse same boss');
body.dataset.gameMode='story';
assert.equal(cinema.cue('leviathan',1),false,'story mode stays isolated');
body.dataset.gameMode='endless';
cinema.setEnabled(false);
assert.equal(cinema.cue('leviathan',1),false,'disabled HUD stays silent');
console.log('PASS V15 boss phase deduplication, reset, story isolation and disable');
